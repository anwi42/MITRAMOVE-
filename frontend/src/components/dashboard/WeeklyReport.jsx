import { useState } from 'react';
import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';

function formatDate(date) {
  return date.toLocaleDateString('en-IN', { year: 'numeric', month: 'short', day: 'numeric' });
}

export default function WeeklyReport({ child, sessions = [] }) {
  const [generating, setGenerating] = useState(false);

  function generateReport() {
    setGenerating(true);
    try {
      const now = new Date();
      const weekAgo = new Date(now);
      weekAgo.setDate(now.getDate() - 7);

      const weekSessions = sessions.filter((s) => new Date(s.createdAt) >= weekAgo);

      const totalSessions = weekSessions.length;
      const avgScore =
        totalSessions > 0
          ? weekSessions.reduce((sum, s) => sum + (s.performance?.accuracy || 0), 0) /
            totalSessions
          : 0;
      const avgDurationMin =
        totalSessions > 0
          ? weekSessions.reduce((sum, s) => sum + (s.duration || 0), 0) / totalSessions / 60
          : 0;
      const bestLevel = weekSessions.reduce(
        (max, s) => Math.max(max, s.performance?.difficultyReached || 0),
        0
      );

      const doc = new jsPDF();

      doc.setFontSize(18);
      doc.setTextColor(124, 58, 237);
      doc.text('MitraMove Weekly Report', 14, 18);

      doc.setFontSize(11);
      doc.setTextColor(40);
      doc.text(`Child: ${child.name}`, 14, 28);
      doc.text(`Report Range: ${formatDate(weekAgo)} - ${formatDate(now)}`, 14, 35);

      doc.setFontSize(13);
      doc.text('Summary', 14, 47);
      doc.setFontSize(11);
      doc.text(`Total Sessions: ${totalSessions}`, 14, 55);
      doc.text(`Average Score: ${avgScore.toFixed(1)}%`, 14, 62);
      doc.text(`Average Duration: ${avgDurationMin.toFixed(1)} min`, 14, 69);
      doc.text(`Best Level Reached: ${bestLevel || '-'}`, 14, 76);

      const tableRows = weekSessions.map((s) => [
        new Date(s.createdAt).toLocaleDateString(),
        `${(s.performance?.accuracy || 0).toFixed(1)}%`,
        `${((s.duration || 0) / 60).toFixed(1)} min`,
        s.performance?.difficultyReached || '-',
        typeof s.recommendedLevel === 'number' ? s.recommendedLevel : '-',
      ]);

      autoTable(doc, {
        startY: 84,
        head: [['Date', 'Score', 'Duration', 'Level', 'Next Level']],
        body: tableRows.length > 0 ? tableRows : [['-', '-', '-', '-', '-']],
        headStyles: { fillColor: [124, 58, 237] },
      });

      const finalY = doc.lastAutoTable ? doc.lastAutoTable.finalY : 90;
      doc.setFontSize(9);
      doc.setTextColor(140);
      doc.text('Generated by MitraMove AI Therapy Platform', 14, finalY + 12);

      doc.save(`${child.name.replace(/\s+/g, '_')}_weekly_report.pdf`);
    } finally {
      setGenerating(false);
    }
  }

  return (
    <div className="card flex items-center justify-between flex-wrap gap-3">
      <div>
        <p className="font-semibold text-gray-800">Weekly Report</p>
        <p className="text-sm text-gray-500">
          {sessions.length === 0 ? 'No sessions yet' : 'Export the last 7 days as a PDF'}
        </p>
      </div>
      <button
        type="button"
        className="btn-primary disabled:opacity-60 disabled:cursor-not-allowed"
        onClick={generateReport}
        disabled={generating}
      >
        {generating ? 'Generating...' : '📄 Download Weekly Report'}
      </button>
    </div>
  );
}
